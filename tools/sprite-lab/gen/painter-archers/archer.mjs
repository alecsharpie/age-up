import { Pic, body, WALK, SWING, STAND, bow, bowFlat, arrow, write, death, DOX, DW } from './common.mjs';
import { TUNIC } from './body.mjs';
const OUT = process.argv[2] || 'out.archer.js';
const CAP = `
..rrR..
.rrRRy.
rrRRRyy
.hsses.
.hassS.
.hsssS.
..SSS..
`;
const QUIVER = `
on.o
.no.
wWWv
wWv.
wWv.
wWv.
wWv.
wWv.
VVv.
.Vv.
`;
const CAP_BLINK = CAP.replace('.hsses.', '.hssSs.');
function hooks(extra = {}) {
  return Object.assign({
    sleeve: 'skin',
    back(p, o) { // quiver on the back, arrows' fletching poking out above the shoulder
      const x = o.ux, y = o.uy;
      p.stamp(x + 2, y + 4, o.pose.noArrows ? QUIVER.replace(/[on]/g, '.') : QUIVER);
    },
    torso(p, o) { p.stamp(5 + o.ux, 8 + o.uy, TUNIC); },
    head(p, o) { p.stamp(5 + o.ux, 1 + o.uy, o.pose.blink ? CAP_BLINK : CAP); if (o.pose.flick) { p.px(5 + o.ux, 1 + o.uy, 'n'); p.px(4 + o.ux, 1 + o.uy, 'n'); } else { p.px(5 + o.ux, 1 + o.uy, 'n'); p.px(4 + o.ux, 0 + o.uy, 'n'); } },
  }, extra);
}
const hang = (s = 0) => ({ farm: [[9, 9], [10 + Math.round(s * 0.5), 12], [11 + Math.round(s), 14]], barm: [[6, 9], [5 - Math.round(s * 0.5), 12], [5 - Math.round(s), 14]] });
function carryBow(p, o, hand) { bow(p, [hand[0] + 1, hand[1] + 1], 6, 1, null); }
function idleFrame(bob, blink, flick) {
  const pose = Object.assign({}, STAND, { bob, blink, flick }, hang());
  return body(pose, hooks({ front(p, o) { carryBow(p, o, [11 + o.ux, 14 + o.uy]); } })).render();
}
function walkFrame(k) {
  const s = SWING[k], pose = Object.assign({}, WALK[k], hang(s));
  return body(pose, hooks({ front(p, o) { carryBow(p, o, [11 + Math.round(s) + o.ux, 14 + o.uy]); } })).render();
}
// shooting poses: bow arm out at shoulder height, grip at (14,9)
const AIM = [[8, 9], [11, 9], [12, 9]];
function shoot(drawArm, bowOpt, extra = {}) {
  const pose = Object.assign({}, STAND, { farm: drawArm, barm: AIM, lean: extra.lean || 0, bob: extra.bob || 0, noArrows: extra.noArrows });
  return body(pose, hooks({
    barmOpt: { uw: 1, hw: 1, hh: 1 },
    front(p, o) { const b = bow(p, [14 + o.ux, 9 + o.uy], 6, bowOpt.bend ?? 2, bowOpt.pull ? [bowOpt.pull[0] + o.ux, bowOpt.pull[1] + o.uy] : null, bowOpt); if (extra.arrow) extra.arrow(p, o); },
  })).render();
}
function mkDeath(pose, ox) { return body(pose, hooks(), DW, 40, ox); }
const DEATH = death(mkDeath, {
  recoil: Object.assign({}, STAND, { lean: -1, farm: [[8, 9], [6, 6], [5, 4]], barm: [[6, 9], [4, 8], [3, 6]] }),
  buckle: { bob: 3, F: [10, 21], B: [8, 21], fk: 2, bk: 2, lean: -1, farm: [[8, 9], [6, 7], [4, 6]], barm: [[6, 9], [4, 10], [3, 12]] },
  lie: Object.assign({}, STAND, { F: [7, 21], B: [6, 21], farm: [[9, 9], [10, 12], [11, 15]], barm: null, noArrows: true }),
}, (p, k) => {
  const X = DOX;
  if (k === 0) bow(p, [X + 13, 12], 6, 1, null, { tilt: 2 });
  if (k === 1) bow(p, [X + 12, 16], 5, 1, null, { tilt: 4 });
  if (k === 2) bow(p, [X + 12, 20], 3, 1, null, { tilt: 4 });
  if (k >= 3) bowFlat(p, X + 9, X + 17, 23, 2);
  if (k === 5) { p.px(X - 3, 23, 'o'); p.ln(X - 2, 23, X + 1, 23, 'W'); p.px(X + 2, 23, 'i'); } // a spilled arrow
});
const frames = {
  idle: [idleFrame(0), idleFrame(0), idleFrame(0, true), idleFrame(1), idleFrame(1, false, true), idleFrame(1)],
  walk: WALK.map((_, k) => walkFrame(k)),
  ready: [
    shoot([[8, 9], [5, 9], [9, 9]], { bend: 3, pull: [9, 9] }, { arrow: (p, o) => arrow(p, 9 + o.ux, 9 + o.uy, 15 + o.ux, 9 + o.uy) }),
    shoot([[8, 9], [5, 9], [9, 9]], { bend: 3, pull: [9, 9] }, { bob: 1, arrow: (p, o) => arrow(p, 9 + o.ux, 9 + o.uy, 15 + o.ux, 9 + o.uy) }),
  ],
  attack: [
    shoot([[8, 9], [4, 8], [7, 8]], { bend: 2, twang: true }),                  // release: string snaps forward, arrow gone
    shoot([[8, 9], [6, 11], [7, 13]], { bend: 2, tilt: 1 }, { lean: -1 }),        // recoil: bow kicks, draw hand drops
    shoot([[8, 9], [7, 6], [4, 4]], { bend: 2 }, { noArrows: false }),           // reach over the shoulder to the quiver
    shoot([[8, 9], [9, 7], [10, 8]], { bend: 2 }, { arrow: (p, o) => arrow(p, 7 + o.ux, 5 + o.uy, 12 + o.ux, 9 + o.uy) }), // arrow out
    shoot([[8, 9], [6, 9], [11, 9]], { bend: 2 }, { arrow: (p, o) => arrow(p, 11 + o.ux, 9 + o.uy, 15 + o.ux, 9 + o.uy) }), // nock
  ],
  death: DEATH,
};
write(OUT, 'archer', '// Archer: felt cap with a feather, bare arms, team tunic, no armour, quiver on the back, short bow. Generated by painter-archers/archer.mjs.', { anchor: [8, 24], anchors: { death: [8 + DOX, 24] }, frames });
for (const [k, l] of Object.entries(frames)) { console.log('==', k); console.log(l[0]); }
