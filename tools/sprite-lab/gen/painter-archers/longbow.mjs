import { body, WALK, SWING, STAND, bow, bowFlat, arrow, write, death, DOX, DW } from './common.mjs';
import { TUNIC } from './body.mjs';
const OUT = process.argv[2] || 'out.longbow.js';
// green hood: pointed liripipe at the back, framing the face, drapes into a capelet over the shoulders
const HOOD = `
.gg....
gGGGf..
.gGGGGf
.gGsses
.gGassS
.gGsssS
..fSSS.
`;
const HOOD_BLINK = HOOD.replace('.gGsses', '.gGssSs');
const CAPE = `
gGGGGf
.fGGf.
`;
const QUIVER = `
on..
.no.
.wv.
.wv.
.wv.
.wv.
.wv.
.Vv.
`;
function hooks(extra = {}) {
  return Object.assign({
    sleeve: 'skin',
    back(p, o) { p.stamp(o.ux + 2, o.uy + 6, o.pose.noArrows ? QUIVER.replace(/[on]/g, '.') : QUIVER); },
    torso(p, o) { p.stamp(5 + o.ux, 8 + o.uy, TUNIC); p.stamp(5 + o.ux, 8 + o.uy, CAPE); },
    head(p, o) { p.stamp(4 + o.ux, 1 + o.uy, o.pose.blink ? HOOD_BLINK : HOOD); if (o.pose.flick) p.put(3 + o.ux, 2 + o.uy, 'hood', 1); },
  }, extra);
}
const hang = (s = 0) => ({ farm: [[9, 9], [10 + Math.round(s * 0.5), 11], [11 + Math.round(s), 12]], barm: [[6, 9], [5 - Math.round(s * 0.5), 12], [5 - Math.round(s), 14]] });
// the yew bow is as tall as the man: at rest the lower tip sits on the ground
function carryBow(p, hand, low = 0) { bow(p, [hand[0] + 1, hand[1] + 1 - low], 10, 1, null); }
function idleFrame(bob, blink, flick) {
  const pose = Object.assign({}, STAND, { bob, blink, flick }, hang());
  return body(pose, hooks({ front(p, o) { carryBow(p, [11 + o.ux, 12]); } })).render();
}
function walkFrame(k) {
  const s = SWING[k], pose = Object.assign({}, WALK[k], hang(s));
  return body(pose, hooks({ front(p, o) { carryBow(p, [11 + Math.round(s) + o.ux, 12 + o.uy], 1); } })).render();
}
const AIM = [[8, 9], [11, 9], [12, 9]];
function shoot(drawArm, bowOpt, extra = {}) {
  const pose = Object.assign({}, STAND, { farm: drawArm, barm: AIM, lean: extra.lean || 0, bob: extra.bob || 0, noArrows: extra.noArrows });
  return body(pose, hooks({
    barmOpt: { uw: 1, hw: 1, hh: 1 },
    front(p, o) { bow(p, [14 + o.ux, 9 + o.uy], 9, bowOpt.bend ?? 2, bowOpt.pull ? [bowOpt.pull[0] + o.ux, bowOpt.pull[1] + o.uy] : null, bowOpt); if (extra.arrow) extra.arrow(p, o); },
  })).render();
}
function mkDeath(pose, ox) { return body(pose, hooks(), DW, 40, ox); }
const DEATH = death(mkDeath, {
  recoil: Object.assign({}, STAND, { lean: -1, farm: [[8, 9], [6, 6], [5, 4]], barm: [[6, 9], [4, 8], [3, 6]] }),
  buckle: { bob: 3, F: [10, 21], B: [8, 21], fk: 2, bk: 2, lean: -1, farm: [[8, 9], [6, 7], [4, 6]], barm: [[6, 9], [4, 10], [3, 12]] },
  lie: Object.assign({}, STAND, { F: [7, 21], B: [6, 21], farm: [[9, 9], [10, 12], [11, 15]], barm: null, noArrows: true }),
}, (p, k) => {
  const X = DOX;
  if (k === 0) bow(p, [X + 13, 12], 9, 1, null, { tilt: 2 });
  if (k === 1) bow(p, [X + 13, 14], 9, 1, null, { tilt: 5 });
  if (k === 2) bow(p, [X + 12, 18], 5, 1, null, { tilt: 7 });
  if (k >= 3) bowFlat(p, X + 2, X + 17, 23, 2);
  if (k === 5) { p.px(X - 4, 23, 'o'); p.ln(X - 3, 23, X + 0, 23, 'W'); p.px(X + 1, 23, 'i'); }
});
const full = [[8, 9], [4, 7], [7, 8]];
const frames = {
  idle: [idleFrame(0), idleFrame(0), idleFrame(0, true), idleFrame(1), idleFrame(1, false, true), idleFrame(1)],
  walk: WALK.map((_, k) => walkFrame(k)),
  // a full draw: string to the ear, the stave deeply bent, a long arrow
  ready: [
    shoot(full, { bend: 4, pull: [7, 8] }, { arrow: (p, o) => arrow(p, 7 + o.ux, 8 + o.uy, 15 + o.ux, 8 + o.uy) }),
    shoot(full, { bend: 4, pull: [7, 8] }, { arrow: (p, o) => arrow(p, 7 + o.ux, 8 + o.uy, 15 + o.ux, 8 + o.uy) }),
    shoot([[8, 9], [4, 7], [8, 8]], { bend: 4, pull: [8, 8] }, { arrow: (p, o) => arrow(p, 8 + o.ux, 8 + o.uy, 15 + o.ux, 8 + o.uy) }),
  ],
  attack: [
    shoot([[8, 9], [3, 7], [5, 7]], { bend: 2, twang: true }),
    shoot([[8, 9], [6, 11], [7, 13]], { bend: 2, tilt: 2 }, { lean: -1 }),
    shoot([[8, 9], [7, 6], [4, 5]], { bend: 2 }),
    shoot([[8, 9], [9, 7], [10, 8]], { bend: 2 }, { arrow: (p, o) => arrow(p, 6 + o.ux, 5 + o.uy, 12 + o.ux, 9 + o.uy) }),
    shoot([[8, 9], [6, 9], [11, 9]], { bend: 2 }, { arrow: (p, o) => arrow(p, 11 + o.ux, 9 + o.uy, 15 + o.ux, 9 + o.uy) }),
  ],
  death: DEATH,
};
write(OUT, 'longbow', '// Longbowman (Britons): green hood and capelet, team tunic, quiver on the back, a yew bow as tall as the man; full draw to the ear. Generated by painter-archers/longbow.mjs.', { anchor: [8, 24], anchors: { death: [8 + DOX, 24] }, frames });
