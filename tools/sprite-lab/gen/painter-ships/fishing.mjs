import * as P from './lib.mjs';
const { grid, set, get, rect, line, poly, stamp, outline, text, WL } = P;
const OUT = './tools/sprite-lab/drafts/pixel.fishing.js';

// Fishing boat: the smallest hull, a lateen (triangular) team sail on a slanting yard, one fisherman at the bow,
// a net with cork floats. work = cast the net and haul it in.
function hull(g) {
  poly(g, [[5, 27], [8, 29], [24, 29], [27, 26], [28, 27], [25, 31], [24, 36], [9, 36], [6, 31]], 'm');
  line(g, 8, 29, 24, 29, 'w'); line(g, 25, 28, 27, 26, 'w'); line(g, 6, 28, 7, 29, 'w');
  for (let y = 31; y <= 35; y++) for (let x = 0; x < 36; x++) if (get(g, x, y) === 'm' && (y >= 33 || x >= 22)) set(g, x, y, 's');
  line(g, 7, 31, 24, 31, 'd');                                    // plank seam
  set(g, 26, 29, 'c'); set(g, 27, 29, 'o');                       // bow eye
}
function mast(g) { line(g, 14, 12, 14, 29, 's'); line(g, 15, 12, 15, 29, 'd'); }
/** lateen sail; b = belly 0..2 (leech bulges toward the bow) */
function sail(g, b) {
  poly(g, [[10, 9], [26 + b, 25], [12, 26], [11.5 - (b ? 0.5 : 0), 17]], 'T');
  for (let y = 0; y < 36; y++) for (let x = 0; x < 36; x++) {
    if (get(g, x, y) !== 'T') continue;
    if (x <= 13 && y < 24) set(g, x, y, 'L');
    else if (y >= 24 || x - y >= 1 - b) set(g, x, y, 'D');
  }
  for (let y = 14; y < 26; y += 4) for (let x = 12; x < 28; x++) if (get(g, x, y) === 'T') set(g, x, y, 'D'); // seams
  line(g, 9, 8, 27, 26, 'd');                                     // yard
}
function fisher(g, pose) {
  // 2 wide; bow side; legs hidden by the gunwale
  const x = 20;
  stamp(g, x - 1, 23, `.nn.\nnNNn\n.Kk.\n.DT.\n.DT.`);
  if (pose === 'hold') { set(g, x + 2, 26, 'k'); }
  if (pose === 'raise') { set(g, x - 1, 25, 'k'); set(g, x + 2, 22, 'k'); set(g, x + 2, 23, 'k'); }
  if (pose === 'throw') { set(g, x + 2, 25, 'k'); set(g, x + 3, 25, 'k'); }
  if (pose === 'haul') { set(g, x + 2, 26, 'k'); set(g, x + 3, 26, 'k'); }
}
const NET_BUNDLE = `
.Nn.
NnnN
.Nb.`;
function net(g, ph) {
  if (ph === 'stow') { stamp(g, 9, 26, `.nNn.\nnNnNn\nbNnNb`); return; }       // coiled at the stern
  if (ph === 'raise') { stamp(g, 21, 19, NET_BUNDLE); return; }
  if (ph === 'fly') {                                                       // opening in the air over the water
    stamp(g, 25, 18, `
....b..
..nNnN.
.nN.Nnb
nN.N.N.
.N.N.Nb
b.N.N..`); line(g, 22, 25, 25, 21, 'N'); return;
  }
  if (ph === 'water') {                                                     // spread on the water, floats bobbing
    stamp(g, 27, 33, `
b.b.b.b.
nNnNnNnN
FuFuFuFF`); line(g, 22, 25, 27, 33, 'N'); return;
  }
  if (ph === 'haul') {                                                      // coming up full, dripping, a fish
    stamp(g, 25, 28, `
.nNn..
nNeiN.
NieiNn
.NnN.F
..F...`); line(g, 22, 26, 25, 28, 'N'); return;
  }
  if (ph === 'over') { stamp(g, 21, 27, `nNnN\nNeiN\nnNen`); stamp(g, 23, 30, `F\n.\nf`); }
}
function boat({ b = 1, flag = 0, foam = 0, moving = false, pose = 'idle', nets = 'stow' }) {
  const g = grid();
  mast(g); sail(g, b); line(g, 8, 5, 9, 8, 'd'); P.pennant(g, 9, 4, flag);
  hull(g);
  outline(g);
  fisher(g, pose); net(g, nets);
  P.lap(g, 9, 24, foam);
  if (moving) P.wake(g, 25, 9, foam);
  return g;
}
const idle = [0, 1, 2, 3, 4, 5].map(k => boat({ b: [0, 1, 2, 2, 1, 0][k], flag: k % 3, foam: k, pose: k === 3 ? 'hold' : 'idle' }));
const walk = [0, 1, 2, 3].map(k => boat({ b: 2, flag: k % 3, foam: k, moving: true }));
const work = [
  boat({ b: 1, pose: 'raise', nets: 'raise', foam: 0 }),
  boat({ b: 1, flag: 1, pose: 'throw', nets: 'fly', foam: 1 }),
  boat({ b: 2, flag: 2, pose: 'hold', nets: 'water', foam: 2 }),
  boat({ b: 2, pose: 'hold', nets: 'water', foam: 3 }),
  boat({ b: 1, flag: 1, pose: 'haul', nets: 'haul', foam: 4 }),
  boat({ b: 0, flag: 2, pose: 'haul', nets: 'over', foam: 5 }),
];
const full = boat({ b: 1 }); for (let x = 0; x < 36; x++) if ('fFu'.includes(full[WL][x])) full[WL][x] = 's';
const death = P.sinking(full, {
  cx: 16,
  steps: [[0, 0, 'hit'], [6, 1], [12, 3], [20, 6], [30, 10], [40, 15], [50, 21], [0, 99, 'flot']],
  hit: g => { stamp(g, 17, 26, `.f\nfF`); },
  debris: (g, k) => { if (k >= 3) stamp(g, 4 - (k - 3), 34, `nNb`); },
  flot: g => {
    stamp(g, 10, 33, `
.DTTL....
DTTTTD..b
FuuuuF.nN`);
    stamp(g, 22, 34, `wms`); stamp(g, 5, 34, `nNb`); stamp(g, 18, 31, `f\nF`); stamp(g, 27, 33, `f\nF`);
  },
});
P.writeDraft(OUT, {
  id: 'fishing', fps: { idle: 4, walk: 8, work: 5, death: 7 },
  header: ['Fishing boat: smallest hull, lateen team sail on a slanting yard, a fisherman at the bow, net with cork floats.',
    'Generated by the ship painter script (scratchpad), stored as literal grids. Faces right; bottom row = waterline (foam).',
    'idle 6 (sail breathes, pennant, foam laps) · walk 4 (bow wave, wake) · work 6 (raise net, cast, on the water, haul, catch over the rail) · death 8.'],
  frames: { idle: idle.map(text), walk: walk.map(text), work: work.map(text), death: death.map(text) },
});
