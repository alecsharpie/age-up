import * as P from './lib.mjs';
const { grid, set, get, rect, line, poly, stamp, outline, text, WL } = P;
const OUT = './tools/sprite-lab/drafts/pixel.transport.js';

// Transport: a wide, deep cargo cog. Round high stem and stern, no oars, steering oar astern, crates/barrels/sacks
// heaped on deck, one stubby mast with a square sail in vertical team/linen stripes, team band along the hull.
function hull(g) {
  poly(g, [[1, 23], [4, 25], [31, 25], [34, 22], [35, 24], [34, 28], [31, 33], [28, 36], [7, 36], [3, 32], [1, 27]], 'm');
  line(g, 3, 25, 31, 25, 'w'); line(g, 1, 23, 3, 24, 'w'); line(g, 32, 24, 34, 22, 'w');
  for (let y = 26; y <= 35; y++) for (let x = 0; x < 36; x++) { const c = get(g, x, y); if (c !== 'm') continue; if (y >= 31 || x >= 29) set(g, x, y, 's'); }
  for (let x = 0; x < 36; x++) { if (get(g, x, 27) !== '.') set(g, x, 27, 'T'); if (get(g, x, 28) !== '.') set(g, x, 28, 'D'); } // team band (wale)
  line(g, 4, 30, 31, 30, 'd'); line(g, 7, 33, 29, 33, 'd');          // strakes
  for (const x of [9, 17, 25]) { set(g, x, 31, 'd'); set(g, x, 32, 'd'); } // frames/bolts
}
function cargo(g) {
  stamp(g, 6, 20, `
wwmm.....
wmms.....
mmss.wwm.
ssss.wms.`);                                  // two crates
  stamp(g, 11, 19, `
.nnN.
nccnN
nnnNN
.NNN.`);                                      // sacks
  stamp(g, 23, 20, `
.wm..
wwms.
mmms.
wwms.
.ms..`);                                      // barrel
  stamp(g, 27, 21, `
wm.
mmms
wmms
.ms.`);                                       // second barrel
}
function mast(g) { line(g, 17, 6, 17, 25, 's'); line(g, 18, 6, 18, 25, 'd'); line(g, 11, 8, 25, 8, 'd'); line(g, 17, 6, 2, 22, 'N'); line(g, 18, 6, 33, 21, 'N'); }
function sail(g, b) {
  poly(g, [[12, 9], [25, 9], [26 + b, 13], [25 + b, 18], [13, 18], [12.5, 13]], 'T');
  for (let y = 9; y < 19; y++) for (let x = 12; x < 29; x++) {
    const c = get(g, x, y); if (c !== 'T') continue;
    const stripe = ((x - 12) >> 1) % 2 === 1;
    const shade = x >= 23 + b || y >= 17; const lit = x <= 13 || y <= 9;
    set(g, x, y, stripe ? (shade ? 'N' : lit ? 'c' : 'n') : (shade ? 'D' : lit ? 'L' : 'T'));
  }
}
function steer(g, ph) { line(g, 3, 26, 1 - (ph % 2), 34, 'w'); set(g, 0 - (ph % 2) + 1, 35, 'w'); }
function ship({ b = 1, flag = 0, foam = 0, moving = false }) {
  const g = grid();
  mast(g); sail(g, b); P.pennant(g, 19, 5, flag);
  hull(g);
  cargo(g);
  outline(g);
  steer(g, moving ? foam : 0);
  P.crew(g, 31, 21); P.crew(g, 4, 22);
  P.lap(g, 7, 28, foam);
  if (moving) P.wake(g, 31, 6, foam);
  return g;
}
const idle = [0, 1, 2, 3, 4, 5].map(k => ship({ b: [0, 1, 2, 2, 1, 0][k], flag: k % 3, foam: k }));
const walk = [0, 1, 2, 3].map(k => ship({ b: 2, flag: k % 3, foam: k, moving: true }));
const full = ship({ b: 1 }); for (let x = 0; x < 36; x++) if ('fFu'.includes(full[WL][x])) full[WL][x] = 's';
const death = P.sinking(full, {
  cx: 18,
  steps: [[0, 0, 'hit'], [-4, 1], [-8, 3], [-12, 6], [-16, 10], [-20, 15], [-24, 22], [0, 99, 'flot']],
  hit: g => { stamp(g, 14, 22, `.g.\nGgG`); },
  debris: (g, k) => { if (k >= 2) { stamp(g, 30 + (k > 4 ? 1 : 0), 33, `wm\nms`); } if (k >= 4) stamp(g, 3, 34, `.nN\nnNN`); },
  flot: g => {
    stamp(g, 8, 32, `
...LTcTL......
.DTnTnTnD.....
FuuuuuuuuF.wm.
...........ms.`);
    stamp(g, 25, 33, `wwm\nmms`); stamp(g, 3, 34, `.nN\nnNN`); stamp(g, 20, 30, `f\nF`); stamp(g, 31, 31, `f\nF`);
  },
});
P.writeDraft(OUT, {
  id: 'transport', fps: { idle: 4, walk: 7, death: 7 },
  header: ['Transport: wide deep cargo cog, round high stem and stern, cargo heaped on deck, steering oar, team band on the hull,',
    'square sail in vertical team/linen stripes. Generated by the ship painter script (scratchpad), stored as literal grids.',
    'idle 6 (sail breathes, pennant, foam laps) · walk 4 (bow wave, wake, steering oar works) · death 8 (lists, sinks, flotsam).'],
  frames: { idle: idle.map(text), walk: walk.map(text), death: death.map(text) },
});
