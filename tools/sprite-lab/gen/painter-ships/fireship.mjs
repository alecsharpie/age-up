import * as P from './lib.mjs';
const { grid, set, get, rect, line, poly, stamp, outline, text, WL } = P;
const OUT = './tools/sprite-lab/drafts/pixel.fireship.js';

// Fire ship: short, low, tarred hull with a team stripe; a raked mast astern with a small square team sail;
// brushwood and pitch barrels heaped amidships; an iron fire-basket on a post at the bow, always burning.
function hull(g) {
  poly(g, [[5, 27], [8, 29], [27, 29], [31, 27], [32, 28], [29, 32], [28, 36], [9, 36], [6, 31]], 's');
  line(g, 7, 29, 27, 29, 'm'); line(g, 28, 28, 31, 27, 'm'); line(g, 5, 27, 7, 28, 'm');
  for (let x = 0; x < 36; x++) if (get(g, x, 30) !== '.') set(g, x, 30, 'T');
  for (let x = 0; x < 36; x++) if (get(g, x, 31) !== '.') set(g, x, 31, 'D');
  for (let y = 32; y <= 35; y++) for (let x = 0; x < 36; x++) if (get(g, x, y) === 's' && (y >= 34 || x >= 25)) set(g, x, y, 'd');
  line(g, 9, 33, 26, 33, 'd');
}
function rigging(g, b) {
  line(g, 10, 13, 11, 29, 's'); line(g, 11, 13, 12, 29, 'd');           // raked mast
  line(g, 6, 14, 17, 14, 'd');
  poly(g, [[7, 15], [17, 15], [17 + b, 19], [16 + b, 23], [8, 23], [7.5, 19]], 'T');
  for (let y = 15; y < 24; y++) for (let x = 7; x < 20; x++) { if (get(g, x, y) !== 'T') continue; if (x <= 8) set(g, x, y, 'L'); else if (x >= 15 + b || y >= 22) set(g, x, y, 'D'); }
  line(g, 11, 13, 25, 23, 'N');                                           // stay to the bow post
}
function load(g) {
  stamp(g, 13, 24, `
..m.w..m..
.wmwmmwms.
wmsmwsmsms
msmsmsmsms
.dd.dd.dd.`);                                                               // brushwood faggots
  stamp(g, 21, 25, `
.ss.
sdds
sdds
.dd.`);                                                                     // pitch barrel
}
function basket(g) {
  line(g, 27, 23, 27, 29, 'I'); line(g, 28, 23, 28, 29, 'Q');            // iron post
  stamp(g, 24, 20, `
ieiiiI.
iQiQiQI
.IQIQI.
..IQI..`);                                                                  // fire-basket
}
// flames: small (idle) ×3 and big (attack) ×4. Origin = basket top-left (24,20)
