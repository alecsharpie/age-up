function ship({ b = 1, flag = 0, foam = 0, moving = false, fire = null }) {
  const g = grid();
  rigging(g, b); P.pennant(g, 12, 11, flag); line(g, 11, 11, 11, 12, 'd');
  hull(g); load(g); basket(g);
  outline(g);
  P.crew(g, 16, 22);
  if (fire) fire(g);
  P.lap(g, 9, 28, foam);
  if (moving) P.wake(g, 30, 9, foam);
  return g;
}
const small = k => g => { stamp(g, 24, 16, SMALL[k % 3]); stamp(g, 24 - (k % 3), 11 - (k % 2), SMOKE[k % 3]); };
const big = k => g => stamp(g, 23, 13, BIG[k]);
const idle = [0, 1, 2, 3, 4, 5].map(k => ship({ b: [0, 1, 2, 2, 1, 0][k], flag: k % 3, foam: k, fire: small(k) }));
const walk = [0, 1, 2, 3].map(k => ship({ b: 2, flag: k % 3, foam: k, moving: true, fire: g => { stamp(g, 23, 16, SMALL[k % 3]); stamp(g, 20 - k, 12, SMOKE[(k + 1) % 3]); } }));
const attack = [0, 1, 2, 3].map(k => ship({ b: 2, flag: k % 3, foam: k, fire: big(k) }));
const full = ship({ b: 1 }); for (let x = 0; x < 36; x++) if ('fFu'.includes(full[WL][x])) full[WL][x] = 'd';
const death = P.sinking(full, {
  cx: 18,
  steps: [[0, 0, 'hit'], [5, 1], [9, 3], [13, 6], [17, 10], [21, 15], [24, 21], [0, 99, 'flot']],
  hit: g => stamp(g, 18, 15, BIG[0]),
  debris: (g, k, sink) => { if (k < 5) stamp(g, 16 + k, 24 + sink - k * 2, SMALL[k % 3]); stamp(g, 12 + k, 6 + k, SMOKE[k % 3]); },
  flot: g => {
    stamp(g, 6, 32, `
.DTTL.........
DTTTTD...wmsd.
FuuuuF..FuuuuF`);
    stamp(g, 22, 34, `ssd`); stamp(g, 27, 33, `iQ\nFF`); stamp(g, 17, 30, `f\nF`); stamp(g, 14, 27, `.g\ngG\n.G`);
  },
});
P.writeDraft(OUT, {
  id: 'fireship', fps: { idle: 6, walk: 8, death: 7 },
  header: ['Fire ship: short low tarred hull with a team stripe, raked mast astern with a small square team sail,',
    'brushwood + pitch barrel amidships, iron fire-basket at the bow. Generated by the ship painter script (scratchpad), stored as literal grids.',
    'idle 6 (flames flicker, smoke wisp, sail, foam) · walk 4 (flames stream aft, bow wave, wake) · attack 4 (basket flares into a forward blaze, subsides) · death 8 (burns, lists, sinks, flotsam).'],
  frames: { idle: idle.map(text), walk: walk.map(text), attack: attack.map(text), death: death.map(text) },
});
