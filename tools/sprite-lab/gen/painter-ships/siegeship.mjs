import * as P from './lib.mjs';
const { grid, set, get, rect, line, poly, stamp, outline, text, WL } = P;
const OUT = './tools/sprite-lab/drafts/pixel.siegeship.js';

// Siege ship (cannon galleon): tall hull with a raised stern castle, two masts (square team main, lateen mizzen),
// gunports along a team band, a heavy bronze bow cannon on a carriage on the foredeck.
function hull(g) {
  poly(g, [[1, 17], [10, 17], [10, 23], [29, 23], [33, 21], [34, 22], [33, 26], [30, 31], [28, 36], [7, 36], [3, 31], [1, 25]], 'm');
  line(g, 1, 17, 10, 17, 'w'); line(g, 10, 23, 29, 23, 'w'); line(g, 30, 22, 33, 21, 'w'); line(g, 1, 18, 1, 24, 'w');
  line(g, 2, 20, 9, 20, 'd');                                               // castle rail line
  for (const x of [3, 6]) stamp(g, x, 21, `bB\nBo`);                       // castle windows, lantern-lit
  for (let y = 24; y <= 35; y++) for (let x = 0; x < 36; x++) { if (get(g, x, y) !== 'm') continue; if (y >= 31 || x >= 28) set(g, x, y, 's'); }
  for (let x = 0; x < 36; x++) { if (get(g, x, 26) !== '.') set(g, x, 26, 'T'); if (get(g, x, 27) !== '.') set(g, x, 27, 'T'); if (get(g, x, 28) !== '.') set(g, x, 28, 'D'); }
  for (const x of [8, 14, 20, 26]) stamp(g, x, 26, `oo\nQo`);              // gunports
  line(g, 4, 30, 30, 30, 'd'); line(g, 7, 33, 28, 33, 'd');
}
function masts(g, b) {
  // main
  line(g, 17, 3, 17, 23, 's'); line(g, 18, 3, 18, 23, 'd'); line(g, 11, 6, 25, 6, 'd'); line(g, 12, 18, 24, 18, 'd');
  poly(g, [[12, 7], [24, 7], [25 + b, 11], [25 + b, 15], [24, 18], [12, 18], [12.5, 12]], 'T');
  for (let y = 7; y < 18; y++) for (let x = 12; x < 28; x++) { if (get(g, x, y) !== 'T') continue; if (x <= 13) set(g, x, y, 'L'); else if (x >= 22 + b || y >= 16) set(g, x, y, 'D'); }
  stamp(g, 16, 10, `.cc.\ncNcN\n.NN.`);                                 // linen roundel on the main sail
  // mizzen lateen on the castle
  line(g, 6, 7, 6, 17, 's'); line(g, 7, 7, 7, 17, 'd');
  poly(g, [[2.5, 7], [12, 16], [4, 17], [3 - b * 0.5, 12]], 'T');
  for (let y = 7; y < 18; y++) for (let x = 0; x < 14; x++) { if (get(g, x, y) !== 'T') continue; if (x <= 3) set(g, x, y, 'L'); else if (y >= 15 || x - y >= -4) set(g, x, y, 'D'); }
  line(g, 2, 6, 12, 16, 'd');
  line(g, 18, 3, 33, 20, 'N'); line(g, 17, 3, 8, 8, 'N');
}
/** bow cannon; back = recoil px */
function cannon(g, back) {
  const x = 22 - back;
  stamp(g, x, 19, `
.bbbbbbbb.
bBBBBBBBBe
.BBBBBBBB.`);                                                               // bronze barrel
  stamp(g, x + 1, 22, `.ms..ms.`); set(g, x + 2, 22, 'w'); set(g, x + 5, 22, 'w');   // carriage + wheels
  stamp(g, 23, 21, `dmmmmmd`);
}
function gunner(g, x, pose) { P.crew(g, x, 19, { tall: true });   /* tall: the body reaches the gunwale (row 23) instead of hovering a row above it */ if (pose === 'ram') { set(g, x + 2, 20, 'k'); line(g, x + 3, 19, x + 5, 19, 'w'); } if (pose === 'cover') { set(g, x - 1, 19, 'k'); } }
function ship({ b = 1, flag = 0, foam = 0, moving = false, back = 0, pose = 'idle', fx = null, dx = 0 }) {
  let g = grid();
  masts(g, b); P.pennant(g, 19, 2, flag); P.pennant(g, 8, 6, (flag + 1) % 3);
  hull(g);
  cannon(g, back);
  outline(g);
  gunner(g, 19 - back, pose);
  if (dx) g = P.shift(g, dx, 0);
  P.lap(g, 7 + dx, 28 + dx, foam);
  if (moving) P.wake(g, 31, 6, foam);
  if (fx) fx(g);
  return g;
}
const FLASH = `
....gg.
.yyYgGg
yyyYYrG
.yyYr..
..r....`;
const PUFF = [`
..gg..
.gggG.
ggGgGG
.gGGG.`, `
...gg..
.gg.gG.
ggGgGG.
.GGgG..`, `
..g....
.g.gg..
...gG..`];
const idle = [0, 1, 2, 3, 4, 5].map(k => ship({ b: [0, 1, 2, 2, 1, 0][k], flag: k % 3, foam: k }));
const walk = [0, 1, 2, 3].map(k => ship({ b: 2, flag: k % 3, foam: k, moving: true }));
const attack = [
  ship({ b: 1, back: 2, dx: -1, pose: 'cover', fx: g => stamp(g, 30, 18, FLASH) }),
  ship({ b: 2, flag: 1, back: 2, foam: 1, pose: 'cover', fx: g => stamp(g, 29, 16, PUFF[0]) }),
  ship({ b: 2, flag: 2, back: 1, foam: 2, pose: 'ram', fx: g => stamp(g, 28, 13, PUFF[1]) }),
  ship({ b: 1, back: 0, foam: 3, pose: 'ram', fx: g => stamp(g, 27, 10, PUFF[2]) }),
];
const full = ship({ b: 1 }); for (let x = 0; x < 36; x++) if ('fFu'.includes(full[WL][x])) full[WL][x] = 's';
const death = P.sinking(full, {
  cx: 18,
  steps: [[0, 0, 'hit'], [-4, 1], [-8, 3], [-12, 6], [-16, 10], [-20, 15], [-24, 22], [0, 99, 'flot']],
  hit: g => { stamp(g, 12, 21, PUFF[0]); stamp(g, 14, 23, `yr\nrR`); },
  debris: (g, k) => { if (k >= 3) stamp(g, 30 + (k > 5 ? 1 : 0), 33, `ws\nms`); },
  flot: g => {
    stamp(g, 8, 32, `
...LTTcTL......
.DTTTTTTTD.....
FuuuuuuuuuF.wmm`);
    stamp(g, 25, 34, `wwms`); stamp(g, 3, 34, `bB`); stamp(g, 18, 30, `f\nF`); stamp(g, 30, 31, `f\nF`);
  },
});
P.writeDraft(OUT, {
  id: 'siegeship', fps: { idle: 4, walk: 7, death: 7 },
  header: ['Siege ship (cannon galleon): tall hull, raised stern castle, square team main sail with a roundel, lateen mizzen,',
    'gunports on a team band, bronze bow cannon on a carriage. Generated by the ship painter script (scratchpad), stored as literal grids.',
    'idle 6 (sails breathe, pennants, foam) · walk 4 (bow wave, wake) · attack 4 (flash + recoil, smoke, run out, puff drifts) · death 8.'],
  frames: { idle: idle.map(text), walk: walk.map(text), attack: attack.map(text), death: death.map(text) },
});
