// Reads the game's index.html and pulls out exactly the drawing vocabulary the lab needs,
// so the lab always renders with the *live* game code (nothing is copied by hand).
// Also owns the one write path back into index.html (applyCase / applyHelpers) with backups.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { balanced, caseSegments, spliceCase, spliceResource, splicePixel, statementEnd } from './splice.js';

export const HERE = path.dirname(fileURLToPath(import.meta.url));
export const ROOT = path.resolve(HERE, '../..');
export const INDEX = path.join(ROOT, 'index.html');
export const BACKUPS = path.join(HERE, 'backups');

export const readIndex = () => fs.readFileSync(INDEX, 'utf8');

export function scriptOf(html) {
  const m = /<script>([\s\S]*?)<\/script>/.exec(html);
  if (!m) throw new Error('no <script> block in index.html');
  return { text: m[1], start: m.index + '<script>'.length };
}

export function grabFunction(src, name) {
  const m = new RegExp('(^|\\n)function ' + name + '\\(').exec(src);
  if (!m) throw new Error('function ' + name + '( not found in index.html');
  const start = m.index + m[1].length;
  const end = balanced(src, start) + 1;
  return { start, end, text: src.slice(start, end) };
}
export function grabLine(src, startsWith) {
  const i = src.indexOf('\n' + startsWith);
  if (i < 0) throw new Error(JSON.stringify(startsWith) + ' not found at a line start in index.html');
  const s = i + 1, e = src.indexOf('\n', s);
  return { start: s, end: e, text: src.slice(s, e) };
}
export function grabObject(src, startsWith) {
  const i = src.indexOf('\n' + startsWith);
  if (i < 0) throw new Error(JSON.stringify(startsWith) + ' not found at a line start in index.html');
  const s = i + 1; let end = balanced(src, s) + 1; if (src[end] === ';') end++;
  return { start: s, end, text: src.slice(s, end) };
}

const LINES = ['const TW=', 'const TEAM=', 'const RES_KINDS=', 'const RES_COLORS=', 'const AGES=', 'const ANIMALS=', 'const BUILD_ORDER=', 'const wpx=', 'const resSprites='];
const OBJECTS = ['const UNITS=', 'const BUILDINGS='];
const FUNCS = ['mulberry32', 'poly', 'shade', 'corners', 'box', 'pyramid', 'flag', 'battlements', 'resSprite', 'drawBuilding', 'human', 'drawUnit', 'drawResource'];

/** Generated classic script: constants + helpers + the three draw functions. Validated before it is served. */
export function gameJs(html = readIndex()) {
  const { text: src } = scriptOf(html);
  const parts = ['// GENERATED by tools/sprite-lab/extract.mjs from index.html at lab start. Do not edit; edit index.html.'];
  for (const l of LINES) parts.push(grabLine(src, l).text);
  for (const o of OBJECTS) parts.push(grabObject(src, o).text);
  for (const f of FUNCS) parts.push(grabFunction(src, f).text);
  // things the draw code may lean on that newer versions of the game added (elevation etc.) — included when present
  for (const l of ['const EPX=']) if (src.includes('\n' + l)) parts.push(grabLine(src, l).text);
  for (const f of ['hCorner', 'heightAt']) if (new RegExp('\\nfunction ' + f + '\\(').test(src)) parts.push(grabFunction(src, f).text);
  // pixel-sprite support: present in the game once `apply helpers` / `apply pixel` have run; otherwise the lab supplies stubs + drafts/helpers.js
  parts.push(src.includes('\nconst PIXELS={};') ? 'const PIXELS={};' : 'const PIXELS={}; // (not yet in the game)');
  parts.push(src.includes('\nconst PIX_CACHE={};') ? 'const PIX_CACHE={};' : 'const PIX_CACHE={};');
  for (const f of ['pixBuild', 'pixDraw']) if (new RegExp('\\nfunction ' + f + '\\(').test(src)) parts.push(grabFunction(src, f).text);
  for (const m of src.matchAll(/\nPIXELS\.([a-z]+)=/g)) { const start = m.index + 1; parts.push(src.slice(start, statementEnd(src, start))); }
  const out = parts.join('\n') + '\n';
  new vm.Script(out, { filename: 'game.generated.js' }); // throws a SyntaxError with line info if extraction went wrong
  return out;
}

const HEX = /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g;
const uniq = a => [...new Set(a)];
function colorsIn(text) { return uniq((text.match(HEX) || []).map(c => c.toLowerCase())); }

export function meta(html = readIndex()) {
  const { text: src } = scriptOf(html);
  const fn = {};
  for (const f of ['drawBuilding', 'drawUnit', 'drawResource', 'resSprite', 'human', 'box', 'pyramid', 'flag', 'battlements']) fn[f] = grabFunction(src, f).text;
  const units = [...grabObject(src, 'const UNITS=').text.matchAll(/^ ([a-z]+):\{/gm)].map(m => m[1]);
  const buildings = [...grabObject(src, 'const BUILDINGS=').text.matchAll(/^ ([a-z]+):\{/gm)].map(m => m[1]);
  const casesOf = t => { const o = {}; for (const s of caseSegments(t)) if (s.types) for (const ty of s.types) o[ty] = s.types; return o; };
  const css = (/<style>([\s\S]*?)<\/style>/.exec(html) || [,''])[1];
  const terrain = grabFunction(src, 'buildTerrain').text;
  const palette = {
    team: colorsIn(grabLine(src, 'const TEAM=').text),
    buildings: colorsIn(fn.drawBuilding + fn.box + fn.pyramid + fn.flag + fn.battlements),
    units: colorsIn(fn.drawUnit + fn.human),
    resources: colorsIn(fn.resSprite + fn.drawResource + grabLine(src, 'const RES_COLORS=').text),
    terrain: colorsIn(terrain),
    ui: colorsIn(css),
  };
  palette.all = uniq(Object.values(palette).flat());
  const pixels = [...src.matchAll(/\nPIXELS\.([a-z]+)=/g)].map(m => m[1]);
  const hasPix = /\nfunction pixDraw\(/.test(src);
  return { units, buildings, resources: ['wood', 'food', 'gold', 'stone'], unitCases: casesOf(fn.drawUnit), buildingCases: casesOf(fn.drawBuilding), fn, palette, pixels, hasPix };
}

export function backup() {
  fs.mkdirSync(BACKUPS, { recursive: true });
  const name = 'index.' + new Date().toISOString().replace(/[:.]/g, '-') + '.html';
  fs.copyFileSync(INDEX, path.join(BACKUPS, name));
  return path.join(BACKUPS, name);
}
export function listBackups() {
  if (!fs.existsSync(BACKUPS)) return [];
  return fs.readdirSync(BACKUPS).filter(f => f.endsWith('.html')).sort().map(f => path.join(BACKUPS, f));
}

/** Rewrite one function of the inline script; returns the new html. Validates the whole script parses. */
function rewriteFunction(html, name, newText) {
  const { text: src, start } = scriptOf(html);
  const g = grabFunction(src, name);
  const newSrc = src.slice(0, g.start) + newText + src.slice(g.end);
  new vm.Script(newSrc, { filename: 'index.html(script)' });
  return html.slice(0, start) + newSrc + html.slice(start + src.length);
}

/** Splice a draft body into index.html. Returns {before, after, html}; writes (with backup) unless dry. */
export function applyCase(kind, type, body, { dry = false, backup: doBackup = true } = {}) {
  const html = readIndex();
  const { text: src } = scriptOf(html);
  const fname = kind === 'building' ? 'drawBuilding' : kind === 'unit' ? 'drawUnit' : 'resSprite';
  const before = grabFunction(src, fname).text;
  const after = kind === 'resource' ? spliceResource(before, type, body) : spliceCase(before, type, body);
  const out = rewriteFunction(html, fname, after);
  if (!dry) { const b = doBackup ? backup() : null; fs.writeFileSync(INDEX, out); return { before, after, backup: b }; }
  return { before, after };
}

/** Insert or replace helper functions right after `battlements` (the game's helper block). */
export function applyHelpers(helpers, { dry = false, backup: doBackup = true } = {}) {
  let html = readIndex();
  const report = [];
  for (const h of helpers) {
    const { text: src, start } = scriptOf(html);
    let newSrc;
    if (new RegExp('(^|\\n)function ' + h.name + '\\(').test(src)) {
      const g = grabFunction(src, h.name); newSrc = src.slice(0, g.start) + h.text + src.slice(g.end); report.push('replaced ' + h.name);
    } else {
      const g = grabFunction(src, 'battlements'); newSrc = src.slice(0, g.end) + '\n' + h.text + src.slice(g.end); report.push('inserted ' + h.name);
    }
    new vm.Script(newSrc, { filename: 'index.html(script)' });
    html = html.slice(0, start) + newSrc + html.slice(start + src.length);
  }
  if (!dry && helpers.length) { if (doBackup) report.push('backup ' + backup()); fs.writeFileSync(INDEX, html); }
  return report;
}

/** Store a painted sprite in the game as `PIXELS.<id>=...;` (creating the PIXELS/PIX_CACHE declarations after `battlements` if needed). */
export function applyPixel(id, specText, { dry = false, backup: doBackup = true } = {}) {
  const html = readIndex();
  const { text: src, start } = scriptOf(html);
  let newSrc = src;
  if (!newSrc.includes('\nconst PIXELS={};')) { const g = grabFunction(newSrc, 'battlements'); newSrc = newSrc.slice(0, g.end) + '\nconst PIXELS={};const PIX_CACHE={};' + newSrc.slice(g.end); }
  newSrc = splicePixel(newSrc, id, specText);
  new vm.Script(newSrc, { filename: 'index.html(script)' });
  const out = html.slice(0, start) + newSrc + html.slice(start + src.length);
  if (!dry) { const b = doBackup ? backup() : null; fs.writeFileSync(INDEX, out); return { backup: b }; }
  return {};
}
